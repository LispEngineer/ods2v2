"""Writes src/ods5_fold_table.h: the simple (one character to one character) upper-case mapping of the
Basic Multilingual Plane, as ranges {first, last, delta, stride}, from Python's unicodedata (Unicode %s).
Usage: python3 -I tools/gen_ods5_fold.py > src/ods5_fold_table.h
Why: VMS compares ODS-5 names case-blind for ISO Latin-1 and UCS-2 letters alike (measured on a VMS-made volume,
ODS5_FORMAT_NOTES.md 4.1: the records for a/A, adiaeresis/Adiaeresis, Alpha/alpha, Zhe/zhe are one name with two
versions, and the order of the directory is that of the upper-cased code points)."""
import unicodedata

m = {}
for cp in range(0x10000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    u = chr(cp).upper()
    if len(u) == 1 and ord(u) != cp and ord(u) < 0x10000:
        m[cp] = ord(u)
cps = sorted(m)
ents, i = [], 0
while i < len(cps):
    lo = cps[i]; d = m[lo] - lo
    j = i
    while j + 1 < len(cps) and cps[j + 1] == cps[j] + 1 and m[cps[j + 1]] - cps[j + 1] == d: j += 1
    k = i
    while k + 1 < len(cps) and cps[k + 1] == cps[k] + 2 and m[cps[k + 1]] - cps[k + 1] == d: k += 1
    if k - i > j - i:
        ents.append((lo, cps[k], d, 2)); i = k + 1
    else:
        ents.append((lo, cps[j], d, 1)); i = j + 1
print('/*\n * MIT License - Copyright (c) 2026 Douglas P. Fields, Jr. (symbolics@lisp.engineer)\n * (see LICENSE: permission is granted, free of charge, to use, copy, modify, merge, publish, distribute,\n * sublicense and/or sell copies of this software, under the terms of the MIT License; THE SOFTWARE IS\n * PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND.)\n */')
print('/* Generated by tools/gen_ods5_fold.py from Python unicodedata %s; do not edit. */' % unicodedata.unidata_version)
print('static const struct { uint16_t lo, hi; int32_t delta; uint8_t stride; } ods5_fold_ranges[] = {')
for lo, hi, d, s in ents:
    print('    { 0x%04X, 0x%04X, %d, %d },' % (lo, hi, d, s))
print('};')
